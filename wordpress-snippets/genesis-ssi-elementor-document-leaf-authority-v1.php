function genesis_ssi_elementor_leaf_v1_authority($page_id, $element_id, $reason = null) {
    $registry = genesis_ssi_elementor_leaf_v1_registry();
    if (!isset($registry[$page_id]) || !isset($registry[$page_id]['leaves'][$element_id])) return null;
    $document = $registry[$page_id];
    $leaf = $document['leaves'][$element_id];
    if ($document['hostname'] !== GENESIS_SSI_ELEMENTOR_LEAF_V1_HOST || ($reason !== null && !in_array($reason, $leaf['reasons'], true))) return null;
    return array('document' => $document, 'leaf' => $leaf);
}

function genesis_ssi_elementor_leaf_v1_permission() {
    if (!is_user_logged_in()) return new WP_Error('genesis_elementor_leaf_unauthorized', 'Authentication is required.', array('status' => 401));
    $host = preg_replace('/^www\./', '', strtolower((string) wp_parse_url(home_url('/'), PHP_URL_HOST)));
    if ($host !== GENESIS_SSI_ELEMENTOR_LEAF_V1_HOST) return new WP_Error('genesis_elementor_leaf_wrong_site', 'Wrong site.', array('status' => 403));
    if (!current_user_can('edit_others_pages')) return new WP_Error('genesis_elementor_leaf_forbidden', 'edit_others_pages is required.', array('status' => 403));
    if (!current_user_can('unfiltered_html')) return new WP_Error('genesis_elementor_leaf_html_forbidden', 'unfiltered_html is required to preserve HTML widget content.', array('status' => 403));
    return true;
}

function genesis_ssi_elementor_leaf_v1_hash($value) {
    return hash('sha256', (string) $value);
}

function genesis_ssi_elementor_leaf_v1_structure($nodes, $path = array()) {
    $rows = array();
    foreach ($nodes as $position => $node) {
        $id = isset($node['id']) ? (string) $node['id'] : '';
        $next = array_merge($path, array($id !== '' ? $id : (string) $position));
        $rows[] = array(
            'path' => implode('/', $next),
            'id' => $id,
            'elType' => isset($node['elType']) ? (string) $node['elType'] : '',
            'widgetType' => isset($node['widgetType']) ? (string) $node['widgetType'] : null,
        );
        if (!empty($node['elements']) && is_array($node['elements'])) {
            $rows = array_merge($rows, genesis_ssi_elementor_leaf_v1_structure($node['elements'], $next));
        }
    }
    return $rows;
}

function genesis_ssi_elementor_leaf_v1_find(&$nodes, $element_id, &$matches) {
    foreach ($nodes as &$node) {
        if (isset($node['id']) && $node['id'] === $element_id) $matches[] =& $node;
        if (!empty($node['elements']) && is_array($node['elements'])) genesis_ssi_elementor_leaf_v1_find($node['elements'], $element_id, $matches);
    }
}

function genesis_ssi_elementor_leaf_v1_setting_hashes($nodes, $path = array()) {
    $hashes = array();
    foreach ($nodes as $position => $node) {
        $id = isset($node['id']) ? (string) $node['id'] : (string) $position;
        $next = array_merge($path, array($id));
        foreach (($node['settings'] ?? array()) as $key => $value) {
            if (is_string($value)) $hashes[implode('/', $next) . '/settings.' . $key] = genesis_ssi_elementor_leaf_v1_hash($value);
        }
        if (!empty($node['elements']) && is_array($node['elements'])) $hashes = array_merge($hashes, genesis_ssi_elementor_leaf_v1_setting_hashes($node['elements'], $next));
    }
    ksort($hashes);
    return $hashes;
}

function genesis_ssi_elementor_leaf_v1_regions($value, $pattern) {
    preg_match_all($pattern, (string) $value, $matches);
    return $matches[0];
}

function genesis_ssi_elementor_leaf_v1_replacement_allowed($before, $after) {
    $patterns = array(
        '/<script\b[\s\S]*?<\/script>/i',
        '/<style\b[\s\S]*?<\/style>/i',
        '/<(?:img|video|audio|source|picture)\b[^>]*>/i',
    );
    foreach ($patterns as $pattern) {
        if (genesis_ssi_elementor_leaf_v1_regions($before, $pattern) !== genesis_ssi_elementor_leaf_v1_regions($after, $pattern)) return false;
    }
    return true;
}

function genesis_ssi_elementor_leaf_v1_semantic_unwrap($value, $hrefs) {
    foreach ($hrefs as $href) {
        $quoted = preg_quote($href, '/');
        $value = preg_replace('/<a\b([^>]*)href=(["\'])' . $quoted . '\2([^>]*)>([\s\S]*?)<\/a>/i', '$4', $value);
    }
    return $value;
}

function genesis_ssi_elementor_leaf_v1_semantic_node($node, $policy, $reason) {
    if ($node->nodeType === XML_TEXT_NODE) {
        $parent = strtolower((string) ($node->parentNode ? $node->parentNode->nodeName : ''));
        $normalized_text = preg_replace('/\s+/u', ' ', trim((string) $node->nodeValue));
        if ($reason !== 'certification') {
            foreach (($policy['allowedTextReplacements'] ?? array()) as $index => $replacement) {
                if ($normalized_text === $replacement['before'] || $normalized_text === $replacement['after']) return array('text' => '__GENESIS_REGISTERED_TEXT_' . $index . '__');
            }
        }
        if (in_array($parent, $policy['allowedTextTags'], true) && trim($node->nodeValue) !== '') return array('text' => '__GENESIS_TEXT__');
        return array('text' => (string) $node->nodeValue);
    }
    if ($node->nodeType === XML_COMMENT_NODE) return array('comment' => (string) $node->nodeValue);
    if ($node->nodeType !== XML_ELEMENT_NODE) return null;
    $tag = strtolower((string) $node->nodeName);
    $attributes = array();
    foreach ($node->attributes as $attribute) {
        $name = strtolower((string) $attribute->nodeName);
        if (preg_match('/^on[a-z]+$/', $name) || in_array($name, array('srcdoc', 'data-code'), true)) return false;
        $value = (string) $attribute->nodeValue;
        if ($name === 'href') {
            foreach ($policy['allowedHrefReplacements'] as $replacement) {
                if ($value === $replacement['before'] || $value === $replacement['after']) $value = '__GENESIS_REGISTERED_HREF__';
            }
        }
        $attributes[$name] = $value;
    }
    ksort($attributes);
    $children = array();
    foreach ($node->childNodes as $child) {
        $normalized = genesis_ssi_elementor_leaf_v1_semantic_node($child, $policy, $reason);
        if ($normalized === false) return false;
        if ($normalized !== null) $children[] = $normalized;
    }
    return array('tag' => $tag, 'attributes' => $attributes, 'children' => $children);
}

function genesis_ssi_elementor_leaf_v1_semantic_canonical($value, $policy, $reason) {
    $marker = $policy['certificationMarker'];
    $value = str_replace($marker, '', (string) $value);
    if ($reason !== 'certification') $value = genesis_ssi_elementor_leaf_v1_semantic_unwrap($value, $policy['allowedAnchorUnwrapHrefs']);
    if (!class_exists('DOMDocument')) return false;
    $document = new DOMDocument('1.0', 'UTF-8');
    $previous = libxml_use_internal_errors(true);
    $loaded = $document->loadHTML('<?xml encoding="UTF-8"><div id="genesis-semantic-root">' . $value . '</div>', LIBXML_HTML_NOIMPLIED | LIBXML_HTML_NODEFDTD);
    libxml_clear_errors();
    libxml_use_internal_errors($previous);
    if (!$loaded) return false;
    $root = $document->documentElement;
    if (!$root) return false;
    return genesis_ssi_elementor_leaf_v1_semantic_node($root, $policy, $reason);
}

function genesis_ssi_elementor_leaf_v1_semantic_allowed($before, $after, $authority, $reason) {
    $policy = $authority['leaf']['semanticPolicy'] ?? null;
    if (!is_array($policy) || !in_array('SEMANTIC_HTML', $authority['leaf']['mutationClasses'] ?? array(), true)) return false;
    if (!genesis_ssi_elementor_leaf_v1_replacement_allowed($before, $after)) return false;
    $marker = $policy['certificationMarker'];
    $before_markers = substr_count($before, $marker);
    $after_markers = substr_count($after, $marker);
    if ($reason === 'certification' && $after_markers !== $before_markers + 1) return false;
    if ($reason === 'rollback' && ($after_markers !== $before_markers - 1 || genesis_ssi_elementor_leaf_v1_hash($after) !== $policy['rollbackLeafSha256'])) return false;
    if ($reason === 'remediation' && $after_markers !== $before_markers) return false;
    foreach ($policy['allowedAnchorUnwrapHrefs'] as $href) {
        $pattern = '/<a\b[^>]*href=(["\'])' . preg_quote($href, '/') . '\1/i';
        preg_match_all($pattern, $before, $before_matches);
        preg_match_all($pattern, $after, $after_matches);
        if (count($after_matches[0]) > count($before_matches[0])) return false;
    }
    $before_tree = genesis_ssi_elementor_leaf_v1_semantic_canonical($before, $policy, $reason);
    $after_tree = genesis_ssi_elementor_leaf_v1_semantic_canonical($after, $policy, $reason);
    return $before_tree !== false && $before_tree === $after_tree;
}

function genesis_ssi_elementor_leaf_v1_context($page_id, $element_id, $reason = null) {
    $authority = genesis_ssi_elementor_leaf_v1_authority($page_id, $element_id, $reason);
    if ($authority === null) return new WP_Error('genesis_elementor_leaf_target_forbidden', 'The exact page, element, leaf, and mutation class must be registered.', array('status' => 403));
    if (!current_user_can('edit_post', $page_id)) return new WP_Error('genesis_elementor_leaf_page_forbidden', 'Exact page edit permission is required.', array('status' => 403));
    if (!class_exists('Elementor\\Plugin')) return new WP_Error('genesis_elementor_leaf_unavailable', 'Elementor is unavailable.', array('status' => 503));
    if (get_post_meta($page_id, '_elementor_edit_mode', true) !== 'builder') return new WP_Error('genesis_elementor_leaf_not_builder', 'Page is not Elementor-managed.', array('status' => 409));
    $document = \Elementor\Plugin::$instance->documents->get($page_id);
    if (!$document || !$document->is_built_with_elementor() || !$document->is_editable_by_current_user()) return new WP_Error('genesis_elementor_leaf_document_unavailable', 'Editable Elementor document is unavailable.', array('status' => 409));
    $raw_json = (string) get_post_meta($page_id, '_elementor_data', true);
    $tree = json_decode($raw_json, true);
    if (!is_array($tree)) return new WP_Error('genesis_elementor_leaf_malformed', 'Elementor document JSON is malformed.', array('status' => 409));
    $matches = array();
    genesis_ssi_elementor_leaf_v1_find($tree, $element_id, $matches);
    if (count($matches) !== 1) return new WP_Error('genesis_elementor_leaf_non_unique', 'Element ID must resolve exactly once.', array('status' => 409));
    $element =& $matches[0];
    if (($element['elType'] ?? '') !== 'widget' || ($element['widgetType'] ?? '') !== $authority['leaf']['widgetType']) return new WP_Error('genesis_elementor_leaf_wrong_widget', 'Registered widget type mismatch.', array('status' => 409));
    if (!isset($element['settings']['html']) || !is_string($element['settings']['html'])) return new WP_Error('genesis_elementor_leaf_missing', 'settings.html is unavailable.', array('status' => 409));
    $structure = genesis_ssi_elementor_leaf_v1_structure($tree);
    return array(
        'document' => $document,
        'tree' => &$tree,
        'element' => &$element,
        'documentHash' => genesis_ssi_elementor_leaf_v1_hash($raw_json),
        'leafHash' => genesis_ssi_elementor_leaf_v1_hash($element['settings']['html']),
        'structure' => $structure,
        'hierarchyHash' => genesis_ssi_elementor_leaf_v1_hash(wp_json_encode($structure)),
        'postContentHash' => genesis_ssi_elementor_leaf_v1_hash(get_post_field('post_content', $page_id, 'raw')),
        'pageSettingsHash' => genesis_ssi_elementor_leaf_v1_hash(wp_json_encode(get_post_meta($page_id, '_elementor_page_settings', true))),
        'globalReferencesHash' => genesis_ssi_elementor_leaf_v1_hash(wp_json_encode(array_filter($structure, function ($row) { return ($row['widgetType'] ?? '') === 'global'; }))),
        'settingHashes' => genesis_ssi_elementor_leaf_v1_setting_hashes($tree),
        'authority' => $authority,
    );
}

function genesis_ssi_elementor_leaf_v1_read(WP_REST_Request $request) {
    $page_id = absint($request->get_param('page_id'));
    $element_id = sanitize_key((string) $request->get_param('element_id'));
    $context = genesis_ssi_elementor_leaf_v1_context($page_id, $element_id);
    if (is_wp_error($context)) return $context;
    return rest_ensure_response(array(
        'ok' => true,
        'pageId' => $page_id,
        'elementId' => $element_id,
        'leaf' => 'settings.html',
        'documentSha256' => $context['documentHash'],
        'leafSha256' => $context['leafHash'],
        'postContentSha256' => $context['postContentHash'],
        'elementCount' => count($context['structure']),
        'hierarchySha256' => $context['hierarchyHash'],
        'widgetType' => 'html',
        'value' => $context['element']['settings']['html'],
    ));
}

function genesis_ssi_elementor_leaf_v1_write(WP_REST_Request $request) {
    $params = $request->get_json_params();
    if (is_array($params) && ($params['mutation_class'] ?? '') === 'SEMANTIC_HTML_ATOMIC') {
        return genesis_ssi_elementor_leaf_v1_write_semantic_atomic($params);
    }
    if (is_array($params) && ($params['mutation_class'] ?? '') === 'SEMANTIC_HTML') {
        return genesis_ssi_elementor_leaf_v1_write_semantic($params);
    }
    if (is_array($params) && array_key_exists('mutation_class', $params)) {
        return genesis_ssi_elementor_leaf_v1_write_registered_media($params);
    }
    if (is_array($params) && array_key_exists('changes', $params)) {
        return genesis_ssi_elementor_leaf_v1_write_many($params);
    }
    $keys = is_array($params) ? array_keys($params) : array();
    sort($keys);
    $expected = array('element_id', 'expected_document_sha256', 'expected_leaf_sha256', 'leaf', 'page_id', 'reason', 'replacement');
    if ($keys !== $expected || ($params['leaf'] ?? '') !== 'settings.html' || !is_string($params['replacement'] ?? null)) {
        return new WP_Error('genesis_elementor_leaf_invalid_request', 'Exact document-leaf request is required.', array('status' => 400));
    }
    $page_id = absint($params['page_id']);
    $element_id = sanitize_key((string) $params['element_id']);
    $context = genesis_ssi_elementor_leaf_v1_context($page_id, $element_id, $params['reason']);
    if (is_wp_error($context)) return $context;
    if (isset($context['authority']['leaf']['semanticPolicy'])) return new WP_Error('genesis_elementor_semantic_class_required', 'Registered semantic leaves require the SEMANTIC_HTML mutation class.', array('status' => 403));
    if (strlen($params['replacement']) > $context['authority']['leaf']['maxBytes']) return new WP_Error('genesis_elementor_leaf_oversized', 'Replacement exceeds the registered byte limit.', array('status' => 413));
    if (!genesis_ssi_elementor_leaf_v1_replacement_allowed($context['element']['settings']['html'], $params['replacement'])) return new WP_Error('genesis_elementor_leaf_protected_region', 'Scripts, styles, and media are immutable for this authority.', array('status' => 403));
    if (!hash_equals($context['documentHash'], (string) $params['expected_document_sha256'])) return new WP_Error('genesis_elementor_leaf_stale_document', 'Document hash conflict.', array('status' => 409));
    if (!hash_equals($context['leafHash'], (string) $params['expected_leaf_sha256'])) return new WP_Error('genesis_elementor_leaf_stale_leaf', 'Leaf hash conflict.', array('status' => 409));
    $before_structure = $context['structure'];
    $before_other_leaves = array();
