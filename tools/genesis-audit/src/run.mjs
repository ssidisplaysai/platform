#!/usr/bin/env node
import fs from "fs";
import path from "path";
import { runScan, buildRepositoryHashSnapshot } from "./scanner.mjs";
import { validateOutputs } from "./schema-validator.mjs";
import { stableStringify, sha256Text } from "./utils.mjs";

const rootDir = path.resolve(process.cwd());
const configPath = path.join(rootDir, "tools/genesis-audit/config/gar-0001.config.json");
const outputDir = path.join(rootDir, "genesis/audits/GAR-0001");

const config = JSON.parse(fs.readFileSync(configPath, "utf8"));

function hashOutputSet(dir) {
  const deterministicFiles = new Set([
    "repository-manifest.json",
    "directory-inventory.json",
    "file-inventory.json",
    "package-inventory.json",
    "source-symbol-inventory.json",
    "import-graph.json",
    "circular-dependency-report.json",
    "api-route-inventory.json",
    "prisma-inventory.json",
    "persistence-access-inventory.json",
    "test-inventory.json",
    "documentation-inventory.json",
    "governance-artifact-inventory.json",
    "registry-inventory.json",
    "security-surface-inventory.json",
    "hygiene-inventory.json",
    "unresolved-analysis-items.json"
  ]);
  const files = fs.readdirSync(dir).filter((f) => deterministicFiles.has(f)).sort();
  const items = files.map((f) => {
    const content = fs.readFileSync(path.join(dir, f), "utf8");
    return `${f}:${sha256Text(content)}`;
  });
  return {
    hash: sha256Text(items.join("\n")),
    files: items
  };
}

function buildHumanReports(summary, locationReasoning, validationResults) {
  const lines = [];
  lines.push("# GAR-0001-Final-Report");
  lines.push("");
  lines.push("Classification legend: VERIFIED | INFERRED | OPINION | RECOMMENDATION | UNRESOLVED");
  lines.push("");
  lines.push("## Disposition");
  lines.push(`VERIFIED: ${summary.disposition}`);
  lines.push("");
  lines.push("## Location Selection");
  lines.push(`VERIFIED: Tooling implemented under tools/genesis-audit based on existing tooling convention.`);
  lines.push(`VERIFIED: Evidence package emitted under genesis/audits/GAR-0001 for additive audit outputs.`);
  lines.push(`OPINION: ${locationReasoning}`);
  lines.push("");
  lines.push("## Inventory Totals");
  lines.push(`VERIFIED: Files scanned = ${summary.totals.filesScanned}`);
  lines.push(`VERIFIED: Directories scanned = ${summary.totals.directories}`);
  lines.push(`VERIFIED: Source files parsed = ${summary.totals.sourceFiles}`);
  lines.push(`VERIFIED: Symbols extracted = ${summary.totals.symbols}`);
  lines.push(`VERIFIED: Graph nodes = ${summary.totals.graphNodes}`);
  lines.push(`VERIFIED: Graph edges = ${summary.totals.graphEdges}`);
  lines.push(`VERIFIED: Unresolved imports = ${summary.totals.unresolvedImports}`);
  lines.push("");
  lines.push("## Determinism");
  lines.push(`VERIFIED: Run hashes = ${summary.determinism.hashes.join(", ")}`);
  lines.push(`VERIFIED: Deterministic match across 3 runs = ${summary.determinism.allEqual}`);
  lines.push("");
  lines.push("## Mutation Check");
  lines.push(`VERIFIED: Pre-scan source snapshot hash = ${summary.mutation.preHash}`);
  lines.push(`VERIFIED: Post-scan source snapshot hash = ${summary.mutation.postHash}`);
  lines.push(`VERIFIED: Source mutation detected = ${summary.mutation.mutated}`);
  lines.push("");
  lines.push("## Validation Results");
  validationResults.forEach((v) => {
    lines.push(`VERIFIED: ${v.command} => ${v.result}`);
  });
  lines.push("");
  lines.push("## Limitations");
  lines.push("UNRESOLVED: Static analysis cannot prove runtime security posture.");
  lines.push("UNRESOLVED: Unknown/binary file semantic parsing is intentionally limited.");
  lines.push("UNRESOLVED: Ownership inference from folder layout is not authoritative.");
  lines.push("");
  return lines.join("\n") + "\n";
}

