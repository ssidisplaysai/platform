function main() {
  const scan1 = runScan({ rootDir, config, outputDir });
  const hash1 = hashOutputSet(outputDir).hash;

  runScan({ rootDir, config, outputDir });
  const hash2 = hashOutputSet(outputDir).hash;

  runScan({ rootDir, config, outputDir });
  const hash3 = hashOutputSet(outputDir).hash;

  const determinism = {
    hashes: [hash1, hash2, hash3],
    allEqual: hash1 === hash2 && hash2 === hash3
  };

  const postFiles = runScan({ rootDir, config, outputDir }).files;
  const pre = scan1.snapshotBefore;
  const post = buildRepositoryHashSnapshot(postFiles, "genesis/audits/GAR-0001/");

  const schemaValidation = validateOutputs(outputDir);

  const validationResults = [
    { command: "schema validation", result: schemaValidation.valid ? "PASS" : "FAIL" },
    { command: "determinism x3", result: determinism.allEqual ? "PASS" : "FAIL" },
    { command: "repository mutation check", result: pre.snapshotHash === post.snapshotHash ? "PASS" : "FAIL" }
  ];

  const disposition = determinism.allEqual && schemaValidation.valid && pre.snapshotHash === post.snapshotHash
    ? "READY WITH DOCUMENTED LIMITATIONS"
    : "NOT READY FOR GAR-0002";

  const summary = {
    scannerVersion: config.scannerVersion,
    totals: scan1.totals,
    determinism,
    mutation: {
      preHash: pre.snapshotHash,
      postHash: post.snapshotHash,
      mutated: pre.snapshotHash !== post.snapshotHash
    },
    disposition
  };

  writeRequiredMarkdown(summary, validationResults);

  const finalReport = buildHumanReports(
    summary,
    "Placement aligns with existing repository tooling segregation and additive audit artifact precedent.",
    validationResults
  );

  fs.writeFileSync(path.join(outputDir, "GAR-0001-Final-Report.md"), finalReport, "utf8");

  fs.writeFileSync(
    path.join(outputDir, "audit-run-manifest.json"),
    stableStringify({
      ...JSON.parse(fs.readFileSync(path.join(outputDir, "audit-run-manifest.json"), "utf8")),
      repositoryMutationGuard: {
        preOutputSnapshot: pre,
        postOutputSnapshot: post,
        mutated: pre.snapshotHash !== post.snapshotHash
      },
      determinism
    }),
    "utf8"
  );

  process.stdout.write(
    JSON.stringify(
      {
        outputDir: normalizeForDisplay(outputDir),
        summary,
        schemaValidation
      },
      null,
      2
    ) + "\n"
  );
}

function normalizeForDisplay(p) {
  return p.split(path.sep).join("/");
}

main();
